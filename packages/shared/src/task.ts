import * as z from 'zod';
import { type NoteIssue, noteIssueSchema } from './issue.ts';
import { NOTE_MAX_LENGTH, noteClientSchema, noteReporterSchema } from './note.ts';

/**
 * A **task** is work that a person writes by hand, with no page and no pin (FRU-657). The worker
 * keeps it with the notes of a site, and the console lists it with them.
 *
 * **It is not a note, and no reader of a note reads it.** A note has a page, a viewport and an
 * anchor, and every reader of `fruitback.note` (the widget, the extension, a connector, a webhook)
 * needs them to draw a pin or to say where it is. A task has none of them. Its own kind makes
 * `parseNote` answer `not-found` for it, which is what a reader of before also answers: no reader of
 * a note ever gets a note without its place, and `NOTE_VERSION` does not move.
 *
 * The same two rules as the note keep its round-trip lossless: no schema default value, and no field
 * the reader cannot rebuild from what is stored.
 */

/** Discriminator of a task among the payloads that the worker keeps. */
export const TASK_KIND = 'fruitback.task';

/** The version a task is written with, and the only one a reader takes. */
export const TASK_VERSION = 1;

/** A title is one line, short enough to read in a column of a board. */
export const TASK_TITLE_MAX_LENGTH = 200;

const isoTimestamp = z.string().refine((value) => !Number.isNaN(Date.parse(value)), {
  message: 'expected an ISO 8601 timestamp',
});

export const taskSchema = z.object({
  kind: z.literal(TASK_KIND),
  v: z.literal(TASK_VERSION),
  /** Generated by the worker. The index of the notes keys the task on it, in its site. */
  id: z.string().min(1),
  createdAt: isoTimestamp,
  /** One line, never empty. */
  title: z
    .string()
    .min(1)
    .max(TASK_TITLE_MAX_LENGTH)
    .refine((value) => value.trim() === value && !/[\r\n]/u.test(value), { message: 'expected one trimmed line' }),
  /** What the person wrote under the title. Absent: nothing. */
  text: z.string().min(1).max(NOTE_MAX_LENGTH).optional(),
  /** The site the task belongs to, as a note names it. */
  client: noteClientSchema.optional(),
  /** Who wrote it. The worker writes it from the session, so `verified` is its word. */
  reporter: noteReporterSchema.optional(),
});

export type Task = z.infer<typeof taskSchema>;

/** What a caller supplies; `kind` and `v` are stamped by `createTask`. */
export type TaskInput = Omit<Task, 'kind' | 'v'>;

export type TaskParseResult =
  | { ok: true; task: Task }
  | { ok: false; reason: 'not-found' }
  | { ok: false; reason: 'unsupported-version'; version: number }
  | { ok: false; reason: 'invalid'; message: string };

/** Build a validated task, stamping the current kind and version. Throws on an invalid input. */
export function createTask(input: TaskInput): Task {
  return taskSchema.parse({ ...input, kind: TASK_KIND, v: TASK_VERSION });
}

/**
 * Validate an untrusted value as a task. Never throws: an operator can edit a row. A payload of
 * another kind, a note included, is `not-found`.
 */
export function parseTask(value: unknown): TaskParseResult {
  if ((value as { kind?: unknown } | null | undefined)?.kind !== TASK_KIND) return { ok: false, reason: 'not-found' };
  const version = (value as { v?: unknown }).v;
  // `Number.isInteger` refuses whatever is not a number: the cast only tells TypeScript.
  if (!Number.isInteger(version) || (version as number) < 1) {
    return { ok: false, reason: 'invalid', message: 'missing or malformed task version' };
  }
  if ((version as number) > TASK_VERSION)
    return { ok: false, reason: 'unsupported-version', version: version as number };

  const result = taskSchema.safeParse(value);
  if (!result.success) {
    return {
      ok: false,
      reason: 'invalid',
      message: result.error.issues.map((issue) => `${issue.path.join('.')}: ${issue.message}`).join('; '),
    };
  }

  return { ok: true, task: result.data };
}

/**
 * A task as a read gives it: the envelope of a note (its number, its stage, its status, its replies),
 * with `task` in place of `note`. Only the fields that a store which keeps the task can fill: no
 * address in a tracker, no file, no agent.
 */
export const taskIssueSchema = noteIssueSchema
  .pick({
    id: true,
    identifier: true,
    title: true,
    stage: true,
    stateName: true,
    status: true,
    updatedAt: true,
    comments: true,
    mine: true,
  })
  .extend({ task: taskSchema });

export type TaskIssue = z.infer<typeof taskIssueSchema>;

/** Whether a read answered a task or a note: `task` is there for a task only. */
export function isTaskIssue(issue: NoteIssue | TaskIssue): issue is TaskIssue {
  return 'task' in issue;
}
